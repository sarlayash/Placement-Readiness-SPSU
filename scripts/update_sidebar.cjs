const fs = require('fs');
const path = require('path');
const file = path.join(__dirname, '../src/components/LeftSidebar.tsx');
let s = fs.readFileSync(file, 'utf8');
s = s.replace(/12-Day FAANG Pathway/g, '15-Day FAANG Pathway');
s = s.replace(/10-Day FAANG Pathway/g, '15-Day FAANG Pathway');
s = s.replace(/12-Day Pathway/g, '15-Day Pathway');
s = s.replace(/10-Day Pathway/g, '15-Day Pathway');
s = s.replace(/>12-Day Planner</g, '>15-Day Planner<');
s = s.replace(/>10-Day Planner</g, '>15-Day Planner<');
s = s.replace(/Complete 12-Day Pathway Planner/g, 'Complete 15-Day Pathway Planner');
s = s.replace(/Complete 10-Day Pathway Planner/g, 'Complete 15-Day Pathway Planner');
fs.writeFileSync(file, s, 'utf8');
console.log('Successfully updated LeftSidebar.tsx to 15-Day');
